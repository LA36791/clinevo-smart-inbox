-- CLINEVO SMART INBOX
-- Oracle Database schema

CREATE TABLE EMAIL_MESSAGE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SENDER VARCHAR2(500),
    SUBJECT VARCHAR2(1000),
    RECEIVED_AT TIMESTAMP,
    BODY CLOB,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE DOCUMENT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ID NUMBER NOT NULL,
    FILE_NAME VARCHAR2(500),
    PAGE_COUNT NUMBER,
    DOCUMENT_TYPE VARCHAR2(100),
    EXTRACTED_TEXT CLOB,
    DOCUMENT_SUMMARY CLOB,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_DOCUMENT_EMAIL
        FOREIGN KEY (EMAIL_ID) REFERENCES EMAIL_MESSAGE(ID)
);

CREATE TABLE DOCUMENT_EVIDENCE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENT_ID NUMBER NOT NULL,
    PAGE_NUMBER NUMBER,
    EVIDENCE_TEXT CLOB,
    CONFIDENCE NUMBER(5,4),
    SOURCE_REFERENCE VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_EVIDENCE_DOCUMENT
        FOREIGN KEY (DOCUMENT_ID) REFERENCES DOCUMENT(ID)
);

CREATE TABLE EXTRACTED_FACT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENT_ID NUMBER NOT NULL,
    FIELD_NAME VARCHAR2(100),
    FIELD_VALUE CLOB,
    CONFIDENCE NUMBER(5,4),
    SOURCE_REFERENCE VARCHAR2(1000),
    PAGE_NUMBER NUMBER,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_FACT_DOCUMENT
        FOREIGN KEY (DOCUMENT_ID) REFERENCES DOCUMENT(ID)
);

CREATE TABLE REVIEW_ACTION (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENT_ID NUMBER NOT NULL,
    ORIGINAL_CATEGORY VARCHAR2(100),
    ORIGINAL_CONFIDENCE NUMBER(5,4),
    REVIEWER_DECISION VARCHAR2(100),
    OVERRIDE_CATEGORY VARCHAR2(100),
    REVIEWER_NAME VARCHAR2(200),
    ACTION_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_REVIEW_DOCUMENT
        FOREIGN KEY (DOCUMENT_ID) REFERENCES DOCUMENT(ID)
);

CREATE INDEX IDX_DOCUMENT_EMAIL
    ON DOCUMENT(EMAIL_ID);

CREATE INDEX IDX_EVIDENCE_DOCUMENT
    ON DOCUMENT_EVIDENCE(DOCUMENT_ID);

CREATE INDEX IDX_FACT_DOCUMENT
    ON EXTRACTED_FACT(DOCUMENT_ID);

CREATE INDEX IDX_REVIEW_DOCUMENT
    ON REVIEW_ACTION(DOCUMENT_ID);
